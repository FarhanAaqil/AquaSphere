"""
Data manifest and source verification utilities for AquaSphere (SIH 26066).

Guarantees data integrity and provenance:
- SHA-256 hashing and verification for all artifacts.
- Metadata verification for remote satellite and Argo providers.
- data/manifest.json registry for data tracking without committing raw binaries.
"""

from __future__ import annotations

import hashlib
import json
import logging
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import requests

from aquasphere.constants import LAT_MAX, LAT_MIN, LON_MAX, LON_MIN

logger = logging.getLogger(__name__)


def compute_file_sha256(path: Path | str, normalize_newlines: bool = False) -> str:
    """Compute the SHA-256 hex digest of a file in streaming chunks.

    If normalize_newlines is True, normalizes CRLF to LF for cross-platform consistency.
    """
    p = Path(path)
    if not p.exists():
        raise FileNotFoundError(f"File not found: {p}")

    if p.is_dir():
        # Directory artefacts (Zarr stores): hash of every file's relative path and content hash,
        # in sorted order, so any added, removed, renamed or changed chunk changes the digest.
        tree = hashlib.sha256()
        for f in sorted(x for x in p.rglob("*") if x.is_file()):
            tree.update(f.relative_to(p).as_posix().encode())
            tree.update(compute_file_sha256(f).encode())
        return tree.hexdigest()

    if normalize_newlines:
        raw = p.read_bytes()
        return hashlib.sha256(raw.replace(b"\r\n", b"\n")).hexdigest()

    hasher = hashlib.sha256()
    with open(p, "rb") as f:
        while chunk := f.read(65536):
            hasher.update(chunk)
    return hasher.hexdigest()


class DataManifest:
    """Registry of dataset artifacts, file hashes, source URLs, and coverage metadata."""

    def __init__(self, manifest_path: Path | str = "data/manifest.json") -> None:
        self.manifest_path = Path(manifest_path)
        self.entries: dict[str, dict[str, Any]] = {}
        if self.manifest_path.exists():
            self.load()

    def load(self) -> None:
        """Load manifest from JSON file."""
        with open(self.manifest_path, encoding="utf-8") as f:
            data = json.load(f)
            self.entries = data.get("artifacts", {})

    def save(self) -> None:
        """Save manifest to JSON file."""
        self.manifest_path.parent.mkdir(parents=True, exist_ok=True)
        payload = {
            "_note": "Data provenance manifest for AquaSphere. Auto-generated by data/manifest.py.",
            "updated_at": datetime.now(UTC).isoformat(),
            "domain": {
                "lat_min": LAT_MIN,
                "lat_max": LAT_MAX,
                "lon_min": LON_MIN,
                "lon_max": LON_MAX,
            },
            "artifacts": self.entries,
        }
        with open(self.manifest_path, "w", encoding="utf-8") as f:
            json.dump(payload, f, indent=2)

    def register_artifact(
        self,
        name: str,
        file_path: Path | str,
        description: str,
        source_url: str | None = None,
        date_range: tuple[str, str] | None = None,
        row_count: int | None = None,
        extra: dict[str, Any] | None = None,
    ) -> dict[str, Any]:
        """Record an artifact's path, SHA-256, and metadata."""
        p = Path(file_path)
        sha256 = compute_file_sha256(p)
        entry: dict[str, Any] = {
            "path": str(p).replace("\\", "/"),
            "size_bytes": (
                sum(f.stat().st_size for f in p.rglob("*") if f.is_file())
                if p.is_dir()
                else p.stat().st_size
            ),
            "sha256": sha256,
            "description": description,
            "registered_at": datetime.now(UTC).isoformat(),
        }
        if source_url:
            entry["source_url"] = source_url
        if date_range:
            entry["date_range"] = list(date_range)
        if row_count is not None:
            entry["row_count"] = row_count
        if extra:
            entry["extra"] = extra

        self.entries[name] = entry
        self.save()
        logger.info("Registered artifact '%s' (%s, SHA: %s...)", name, p.name, sha256[:12])
        return entry

    def verify_artifact(self, name: str) -> bool:
        """Verify that an artifact exists on disk and matches its registered SHA-256."""
        if name not in self.entries:
            raise KeyError(f"Artifact '{name}' not found in manifest")

        entry = self.entries[name]
        p = Path(entry["path"])
        if not p.exists():
            logger.warning("Artifact '%s' does not exist at %s", name, p)
            return False

        current_hash = compute_file_sha256(p)
        matched = current_hash == entry["sha256"]
        if not matched and p.suffix.lower() in [
            ".csv",
            ".tsv",
            ".txt",
            ".json",
            ".yaml",
            ".yml",
            ".md",
        ]:
            # Handle Git checkout line-ending differences (Windows CRLF vs Linux LF)
            norm_hash = compute_file_sha256(p, normalize_newlines=True)
            if entry["sha256"] == norm_hash:
                matched = True
            else:
                raw = p.read_bytes()
                crlf_hash = hashlib.sha256(
                    raw.replace(b"\r\n", b"\n").replace(b"\n", b"\r\n")
                ).hexdigest()
                if entry["sha256"] == crlf_hash:
                    matched = True

        if not matched:
            logger.error(
                "Hash mismatch for '%s': expected %s, got %s", name, entry["sha256"], current_hash
            )
        return bool(matched)


def verify_erddap_dataset(
    dataset_id: str,
    base_url: str = "https://www.ncei.noaa.gov/erddap/info",
    expected_variable: str = "sst",
    timeout_s: float = 8.0,
) -> dict[str, Any]:
    """Fetch ERDDAP dataset metadata and verify target variable presence and domain.

    Returns dict with verification status and metadata summary.
    """
    url = f"{base_url}/{dataset_id}/index.json"
    result: dict[str, Any] = {
        "dataset_id": dataset_id,
        "source": "erddap",
        "verified": False,
        "variables": [],
        "notes": "",
    }

    try:
        resp = requests.get(url, timeout=timeout_s)
        resp.raise_for_status()
        data = resp.json()

        rows = data.get("table", {}).get("rows", [])
        var_names = [r[1] for r in rows if r[0] == "variable"]
        result["variables"] = var_names

        if expected_variable in var_names:
            result["verified"] = True
            result["notes"] = f"Found target variable '{expected_variable}' in {dataset_id}."
        else:
            result["notes"] = (
                f"Target variable '{expected_variable}' missing from: {var_names[:8]}."
            )
    except Exception as exc:
        result["notes"] = f"Remote check failed or timed out: {exc}"

    return result

"""
Coverage report for the Phase 2 data (blueprint §11: report sample counts with every stratum).

    python -m aquasphere.data.coverage

Writes docs/results/data_coverage.json and .md and registers the store and Argo tables in
data/manifest.json with their SHA-256 hashes.
"""

from __future__ import annotations

import argparse
import json
import logging
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from aquasphere.constants import STANDARD_DEPTHS
from aquasphere.data.argo_ingest import OUTPUT as ARGO_TABLE
from aquasphere.data.collocate_nio import OUTPUT as COLLOCATED
from aquasphere.data.manifest import DataManifest
from aquasphere.data.satellite_fetch import STORE_PATH
from aquasphere.data.sources import SOURCES
from aquasphere.data.store import SATELLITE_VARS, SurfaceZarrStore

logger = logging.getLogger(__name__)

OUT_JSON = Path("docs/results/data_coverage.json")
OUT_MD = Path("docs/results/data_coverage.md")
BOB_LON = 78.0  # Arabian Sea / Bay of Bengal split used everywhere in the project


def monsoon_season(month: int) -> str:
    if month in (6, 7, 8, 9):
        return "SW monsoon (Jun-Sep)"
    if month in (12, 1, 2):
        return "NE monsoon (Dec-Feb)"
    return "Inter-monsoon (Mar-May, Oct-Nov)"


def store_coverage(store: SurfaceZarrStore) -> dict[str, Any]:
    """Per variable: days with data, and the share of ocean cells covered on those days, by year."""
    dates = pd.to_datetime(pd.Series(store.dates))
    years = dates.dt.year.to_numpy()
    # Ocean = cells where SST is present on most days (OISST is the most complete product)
    sst_valid = np.isfinite(np.asarray(store.root["sst"][:: max(1, len(store.dates) // 60)]))
    ocean = sst_valid.mean(axis=0) > 0.5
    n_ocean = int(ocean.sum())
    out: dict[str, Any] = {
        "n_dates": len(store.dates),
        "first": store.dates[0],
        "last": store.dates[-1],
        "ocean_cells": n_ocean,
        "variables": {},
    }
    for v in SATELLITE_VARS:
        arr = store.root[v]
        per_day = np.empty(len(store.dates))
        for t0 in range(0, len(store.dates), 64):  # stream in blocks to bound memory
            block = np.isfinite(np.asarray(arr[t0 : t0 + 64]))[:, ocean]
            per_day[t0 : t0 + len(block)] = block.mean(axis=1) if n_ocean else 0.0
        has = per_day > 0
        by_year = {
            int(y): {
                "days": int(has[years == y].sum()),
                "ocean_cover": round(float(per_day[(years == y) & has].mean()), 3)
                if has[years == y].any()
                else 0.0,
            }
            for y in np.unique(years)
        }
        first = store.dates[int(np.argmax(has))] if has.any() else None
        out["variables"][v] = {
            "days_with_data": int(has.sum()),
            "first_day": first,
            "by_year": by_year,
        }
    return out


def argo_coverage(df: pd.DataFrame) -> dict[str, Any]:
    d = pd.to_datetime(df["date"])
    region = np.where(df["lon"] >= BOB_LON, "Bay of Bengal", "Arabian Sea")
    season = d.dt.month.map(monsoon_season)
    out: dict[str, Any] = {
        "profiles": len(df),
        "floats": int(df["float_id"].nunique()),
        "first": str(d.min().date()),
        "last": str(d.max().date()),
        "by_year": {int(k): int(v) for k, v in d.dt.year.value_counts().sort_index().items()},
        "by_region": {str(k): int(v) for k, v in pd.Series(region).value_counts().items()},
        "by_season": {str(k): int(v) for k, v in season.value_counts().items()},
        "by_region_season": {
            f"{r} | {s}": int(n)
            for (r, s), n in pd.Series(1, index=pd.MultiIndex.from_arrays([region, season]))
            .groupby(level=[0, 1])
            .size()
            .items()
        },
        "observed_by_depth": {int(z): int(df[f"m_{z}"].sum()) for z in STANDARD_DEPTHS},
    }
    if "data_mode" in df.columns:
        out["by_data_mode"] = {str(k): int(v) for k, v in df["data_mode"].value_counts().items()}
    avail = [c for c in df.columns if c.endswith("_avail")]
    if avail:
        out["channel_availability"] = {
            c.removesuffix("_avail"): round(float(df[c].mean()), 3) for c in avail
        }
    return out


def to_markdown(report: dict[str, Any]) -> str:
    s = report["store"]
    a = report["argo"]
    lines = [
        "# Data coverage (auto-generated by aquasphere.data.coverage, do not edit)",
        "",
        f"Generated {report['generated_at']}.",
        "",
        f"## Surface store: {s['first']} to {s['last']} ({s['n_dates']} days, {s['ocean_cells']} ocean cells)",
        "",
        "| Variable | Source | Days with data | First day |",
        "|---|---|---|---|",
    ]
    owner = {v: spec for spec in SOURCES.values() for v in spec.variables}
    for v, info in s["variables"].items():
        src = owner[v].dataset_id if v in owner else "?"
        lines.append(f"| {v} | {src} | {info['days_with_data']} | {info['first_day']} |")
    lines += [
        "",
        f"## Argo: {a['profiles']} profiles from {a['floats']} floats, {a['first']} to {a['last']}",
        "",
        "| Year | Profiles |",
        "|---|---|",
        *[f"| {y} | {n} |" for y, n in a["by_year"].items()],
        "",
        "| Region / season | Profiles |",
        "|---|---|",
        *[f"| {k.replace(' | ', ' · ')} | {n} |" for k, n in sorted(a["by_region_season"].items())],
        "",
    ]
    if "by_data_mode" in a:
        lines += [
            "Data mode: "
            + ", ".join(f"{k} {v}" for k, v in sorted(a["by_data_mode"].items()))
            + " (D delayed, A adjusted, R real-time).",
            "",
        ]
    if "channel_availability" in a:
        lines += [
            "Channel availability at profiles: "
            + ", ".join(f"{k} {v:.0%}" for k, v in a["channel_availability"].items())
            + ".",
            "",
        ]
    return "\n".join(lines)


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    p = argparse.ArgumentParser(
        description="Coverage report and manifest registration for Phase 2 data"
    )
    p.add_argument("--store", default=str(STORE_PATH))
    p.add_argument("--argo", default=str(COLLOCATED if COLLOCATED.exists() else ARGO_TABLE))
    p.add_argument("--no-manifest", action="store_true")
    a = p.parse_args()

    store = SurfaceZarrStore(a.store)
    argo = pd.read_parquet(a.argo)
    report: dict[str, Any] = {
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "store_path": Path(a.store).as_posix(),
        "argo_path": Path(a.argo).as_posix(),
        "store": store_coverage(store),
        "argo": argo_coverage(argo),
    }
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps(report, indent=1), encoding="utf-8")
    OUT_MD.write_text(to_markdown(report), encoding="utf-8")
    logger.info("Wrote %s and %s", OUT_JSON, OUT_MD)

    if not a.no_manifest:
        m = DataManifest()
        m.register_artifact(
            "surface_store_nio",
            a.store,
            description="Real 0.25° daily surface store (OISST v2.1, CoastWatch altimetry, SMAP SSS, NCEI blended winds)",
            source_url="https://coastwatch.pfeg.noaa.gov/erddap ; https://coastwatch.noaa.gov/erddap",
            date_range=(report["store"]["first"], report["store"]["last"]),
            extra={"synthetic": False, "datasets": {k: s.dataset_id for k, s in SOURCES.items()}},
        )
        for name, path, desc in (
            (
                "argo_nio_2015_2025",
                ARGO_TABLE,
                "Argo profiles 2015-2025, QC 1, PCHIP to 15 depths, with data mode",
            ),
            (
                "argo_nio_collocated",
                COLLOCATED,
                "Argo profiles collocated with the real surface store",
            ),
        ):
            if path.exists():
                t = pd.read_parquet(path)
                m.register_artifact(
                    name,
                    path,
                    description=desc,
                    source_url="https://argovis-api.colorado.edu",
                    date_range=(str(t["date"].min()), str(t["date"].max())),
                    row_count=len(t),
                )


if __name__ == "__main__":
    main()
